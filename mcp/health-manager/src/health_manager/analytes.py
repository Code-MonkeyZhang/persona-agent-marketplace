_ENTRIES = [Analyte(*row) for row in _RAW_ROWS]
ANALYTES: dict[str, Analyte] = {e.name: e for e in _ENTRIES}
ALIASES: dict[str, str] = {alias: e.name for e in _ENTRIES for alias in e.aliases}

_PAREN_RE = re.compile(r"[（(][^（）()]*[）)]")


def normalize_analyte(name: str) -> str | None:
    """Resolve a spoken or written analyte name to its standard name.

    - Accepts dictionary aliases like Scr or CREA and bracketed spellings
    - Returns None when the name matches nothing known
    """
    n = (name or "").strip()
    if not n:
        return None
    for candidate in (n, _PAREN_RE.sub("", n).strip()):
        if candidate in ANALYTES:
            return candidate
        if candidate in ALIASES:
            return ALIASES[candidate]
    return None


def judge_flag(
    value_num: float | None, ref_low: float | None, ref_high: float | None
) -> str | None:
    """Compare a numeric value against its reference range.

    - Returns "H" above the high bound, "L" below the low bound
    - Returns None when the value or both bounds are missing - never guesses
    """
    if value_num is None or (ref_low is None and ref_high is None):
        return None
    if ref_high is not None and value_num > ref_high:
        return "H"
    if ref_low is not None and value_num < ref_low:
        return "L"
    return None


def check_extreme(name: str, value: float) -> None:
    """Reject absurd values against the dictionary bounds before storing."""
    lo, hi = _BOUNDS.get(name, (None, None))
    if (lo is not None and value < lo) or (hi is not None and value > hi):
        raise ValueError(f"{name}值 {value} 超出合理范围，请检查")


def num(value: float) -> str:
    """Trim a trailing .0 so numbers read like the report sheet."""
    return str(int(value)) if float(value).is_integer() else str(value)


def ref_text(low: float | None, high: float | None) -> str | None:
    """Human text of a reference range, like 57-97 or ≤150."""
    if low is not None and high is not None:
        return f"{num(low)}-{num(high)}"
    if high is not None:
        return f"≤{num(high)}"
    if low is not None:
        return f"≥{num(low)}"
    return None
